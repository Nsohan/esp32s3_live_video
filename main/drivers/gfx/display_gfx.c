void gfx_draw_app_tile(int x, int y, int size, IconType icon, const char *label, uint16_t bg_color, bool selected)
{
    int radius = 12;
    uint16_t tile_color = selected ? COLOR_WHITE : bg_color;
    uint16_t icon_color = selected ? COLOR_BLACK : COLOR_WHITE;

    gfx_fill_round_rect(x, y, size, size, radius, tile_color);

    if (selected) {
        gfx_draw_round_rect(x - 2, y - 2, size + 4, size + 4, radius + 2, COLOR_CYAN_ACCENT);
    }

    gfx_draw_icon(x + size / 2, y + size / 2, icon, icon_color);

    if (label) {
        gfx_draw_string_centered(x - 10, y + size + 4, size + 20, label, COLOR_WHITE, COLOR_BLACK, 1);
    }
}
