void gfx_fill_rect(int x, int y, int w, int h, uint16_t color)
{
    display_draw_color_block(x, y, w, h, color);
}

void gfx_draw_rect(int x, int y, int w, int h, uint16_t color)
{
    if (w <= 0 || h <= 0) return;
    gfx_fill_rect(x, y, w, 1, color);
    gfx_fill_rect(x, y + h - 1, w, 1, color);
    gfx_fill_rect(x, y, 1, h, color);
    gfx_fill_rect(x + w - 1, y, 1, h, color);
}

void gfx_fill_round_rect(int x, int y, int w, int h, int r, uint16_t color)
{
    if (w <= 0 || h <= 0) return;
    if (r > w / 2) r = w / 2;
    if (r > h / 2) r = h / 2;
    if (r <= 0) {
        gfx_fill_rect(x, y, w, h, color);
        return;
    }

    size_t pixels = w * h;
    uint16_t *buf = (uint16_t *)heap_caps_malloc(pixels * sizeof(uint16_t), MALLOC_CAP_DMA | MALLOC_CAP_8BIT);
    if (!buf) buf = (uint16_t *)malloc(pixels * sizeof(uint16_t));
    if (!buf) {
        gfx_fill_rect(x, y, w, h, color);
        return;
    }

    uint16_t be_color = SWAP_BYTES(color);
    uint16_t be_bg = 0x0000;

    for (int dy = 0; dy < h; dy++) {
        for (int dx = 0; dx < w; dx++) {
            bool inside = true;
            if (dx < r && dy < r) {
                inside = ((r - dx) * (r - dx) + (r - dy) * (r - dy)) <= (r * r);
            } else if (dx >= w - r && dy < r) {
                int d = dx - (w - r - 1);
                inside = (d * d + (r - dy) * (r - dy)) <= (r * r);
            } else if (dx < r && dy >= h - r) {
                int d = dy - (h - r - 1);
                inside = ((r - dx) * (r - dx) + d * d) <= (r * r);
            } else if (dx >= w - r && dy >= h - r) {
                int d1 = dx - (w - r - 1);
                int d2 = dy - (h - r - 1);
                inside = (d1 * d1 + d2 * d2) <= (r * r);
            }

            buf[dy * w + dx] = inside ? be_color : be_bg;
        }
    }

    display_draw_bitmap_block(x, y, w, h, buf);
    free(buf);
}

void gfx_draw_round_rect(int x, int y, int w, int h, int r, uint16_t color)
{
    gfx_fill_rect(x + r, y, w - 2 * r, 1, color);
    gfx_fill_rect(x + r, y + h - 1, w - 2 * r, 1, color);
    gfx_fill_rect(x, y + r, 1, h - 2 * r, color);
    gfx_fill_rect(x + w - 1, y + r, 1, h - 2 * r, color);
}

void gfx_draw_char(int x, int y, char c, uint16_t color, uint16_t bg, int scale)
{
    if (c < 32 || c > 126) c = ' ';
    const uint8_t *glyph = font8x16[c - 32];

    int char_w = 8 * scale;
    int char_h = 16 * scale;
    size_t pixels = char_w * char_h;

    uint16_t *buf = (uint16_t *)heap_caps_malloc(pixels * sizeof(uint16_t), MALLOC_CAP_DMA | MALLOC_CAP_8BIT);
    if (!buf) buf = (uint16_t *)malloc(pixels * sizeof(uint16_t));
    if (!buf) return;

    uint16_t be_color = SWAP_BYTES(color);
    uint16_t be_bg = SWAP_BYTES(bg);

    for (int row = 0; row < 16; row++) {
        uint8_t line = glyph[row];
        for (int col = 0; col < 8; col++) {
            uint16_t pixel_color = (line & (0x80 >> col)) ? be_color : be_bg;
            for (int sy = 0; sy < scale; sy++) {
                for (int sx = 0; sx < scale; sx++) {
                    int px = col * scale + sx;
                    int py = row * scale + sy;
                    if (px < char_w && py < char_h) {
                        buf[py * char_w + px] = pixel_color;
                    }
                }
            }
        }
    }

    display_draw_bitmap_block(x, y, char_w, char_h, buf);
    free(buf);
}

void gfx_draw_string(int x, int y, const char *str, uint16_t color, uint16_t bg, int scale)
{
    if (!str) return;
    int cur_x = x;
    while (*str) {
        if (*str == '\n') {
            y += 18 * scale;
            cur_x = x;
        } else {
            gfx_draw_char(cur_x, y, *str, color, bg, scale);
            cur_x += 8 * scale;
        }
        str++;
    }
}

void gfx_draw_string_centered(int x, int y, int w, const char *str, uint16_t color, uint16_t bg, int scale)
{
    if (!str) return;
    int str_len = strlen(str);
    int total_w = str_len * 8 * scale;
    int start_x = x + (w - total_w) / 2;
    if (start_x < x) start_x = x;
    gfx_draw_string(start_x, y, str, color, bg, scale);
}

